def _ind(name: str, en: str, where: str, body: str, imply: list | None = None) -> str:
    """一張指標卡：名稱、出處、說明、含義速查（↑↓ 各 imply 什麼）。"""
    imply_html = ""
    if imply:
        rows = "".join(
            f'<span class="gd-dir {cls}">{label}</span><span>{text}</span>'
            for cls, label, text in imply)
        imply_html = f'<div class="gd-imply">{rows}</div>'
    return (f'<div class="gd-ind">'
            f'<div class="gd-name">{name}<span class="gd-en">{en}</span></div>'
            f'<div class="gd-where">{where}</div>'
            f'{body}{imply_html}</div>')


def _chain(*nodes: str) -> str:
    parts = []
    for i, node in enumerate(nodes):
        if i:
            parts.append('<span class="gd-arr">→</span>')
        parts.append(f'<span class="gd-node">{node}</span>')
    return f'<div class="gd-chain">{"".join(parts)}</div>'


def _table(headers: list[str], rows: list[list[str]]) -> str:
    head = "".join(f"<th>{h}</th>" for h in headers)
    body = "".join(
        "<tr>" + "".join(f"<td>{cell}</td>" for cell in row) + "</tr>"
        for row in rows)
    return (f'<div class="table-wrap"><table><thead><tr>{head}</tr></thead>'
            f'<tbody>{body}</tbody></table></div>')


